using System.Collections.Frozen;
using System.Text.Json;

namespace MatterFlow.Configuration.Contracts;

/// <summary>One icon of the Task Type icon library (<c>contracts/task-type-icons.json</c>).</summary>
/// <param name="Key">Stable kebab-case id (a Tabler Icons outline name); this is what <c>TaskType.IconKey</c> stores.</param>
/// <param name="Label">Human label shown in the picker.</param>
/// <param name="Category">Picker category (EDRM stage or General, Data &amp; systems, Communication, Admin).</param>
public sealed record TaskTypeIconInfo(string Key, string Label, string Category);

/// <summary>
/// The allow-list of Task Type icon keys. The source of truth is <c>contracts/task-type-icons.json</c> (generated by <c>tools/icons</c> and
/// embedded here); the Angular library is generated from the same file and a unit test keeps both in step. Icons are never uploaded.
/// </summary>
public static class TaskTypeIcons
{
    private const string ResourceName = "contracts.task-type-icons.json";

    private static readonly Lazy<(string DefaultKey, IReadOnlyList<TaskTypeIconInfo> All, FrozenSet<string> Keys)> Loaded = new(Load);

    /// <summary>The icon every new and existing Task Type starts with.</summary>
    public static string DefaultKey => Loaded.Value.DefaultKey;

    /// <summary>Every allowed icon.</summary>
    public static IReadOnlyList<TaskTypeIconInfo> All => Loaded.Value.All;

    /// <summary>True when <paramref name="key"/> is exactly one of the allowed keys (case-sensitive).</summary>
    public static bool IsValid(string? key) => key is not null && Loaded.Value.Keys.Contains(key);

    private static (string, IReadOnlyList<TaskTypeIconInfo>, FrozenSet<string>) Load()
    {
        using var stream = typeof(TaskTypeIcons).Assembly.GetManifestResourceStream(ResourceName)
            ?? throw new InvalidOperationException($"Embedded resource '{ResourceName}' not found.");
        return Parse(stream);
    }

    internal static (string DefaultKey, IReadOnlyList<TaskTypeIconInfo> All, FrozenSet<string> Keys) Parse(Stream json)
    {
        using var doc = JsonDocument.Parse(json);
        var all = doc.RootElement.GetProperty("icons").EnumerateArray()
            .Select(i => new TaskTypeIconInfo(i.GetProperty("key").GetString()!, i.GetProperty("label").GetString()!, i.GetProperty("category").GetString()!))
            .ToList();
        return (doc.RootElement.GetProperty("defaultKey").GetString()!, all, all.Select(i => i.Key).ToFrozenSet(StringComparer.Ordinal));
    }
}
