fs.mkdirSync(process.env.SHOTS, { recursive: true });
await page.screenshot({ path: `${process.env.SHOTS}/dup-names-1366.jpg`, type: 'jpeg', quality: 70 });
for (const r of st.requests.filter((r) => /rows|export/.test(r))) console.log(decodeURIComponent(r.replace(/%23/g, '#')), '   <-- raw:', r);
