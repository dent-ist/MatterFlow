import fs from 'node:fs';
import { boot, SIZES } from './lib.mjs';
import { createState } from './mock.mjs';
const [dist, portArg] = process.argv.slice(2);
const st = createState();
const h = await boot({ dist, port: Number(portArg), state: st });
const { page, base } = h;
await page.goto(base + '/reports/8');
await page.getByRole('button', { name: 'Run Report' }).click();
await page.locator('tbody tr[data-record-id]').first().waitFor();
await page.locator('th[data-col="Name (2)"] button').click();
await page.getByRole('button', { name: /^Filters/ }).click();
await page.waitForTimeout(300);
const f = page.locator('input[data-filter="c1"]');
await f.fill('smith');
await page.waitForTimeout(900);
await page.locator('[data-export-csv]').click();
