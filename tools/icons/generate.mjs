// Generates the Task Type icon library from the curated list in catalog.mjs and Tabler Icons (MIT, outline set, build-time source only).
//
//   npm ci --prefix tools/icons && node tools/icons/generate.mjs
//
// Writes:
//   contracts/task-type-icons.json                                     shared contract: default key + every allowed key with label/category/keywords
//                                                                      (embedded into the API for validation; the frontend test compares both)
//   frontend/src/app/shared/icons/task-type-icon-paths.generated.ts   key -> inner SVG markup (lazy-loaded chunk shown on every screen)
//   frontend/src/app/shared/icons/task-type-icon-catalog.generated.ts key/label/category/keywords (lazy-loaded chunk used by the picker)
// Fails when a key is missing from Tabler's outline set, is duplicated, is not kebab-case, or an SVG contains anything but simple shapes.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATEGORIES, DEFAULT_ICON_KEY, ICONS } from './catalog.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const tabler = join(here, 'node_modules', '@tabler', 'icons');
if (!existsSync(tabler)) {
  console.error('Run `npm ci --prefix tools/icons` first.');
  process.exit(1);
}
const tablerVersion = JSON.parse(readFileSync(join(tabler, 'package.json'), 'utf8')).version;

const icons = [];
const seen = new Set();
const labels = new Set();
const problems = [];
for (const category of Object.keys(ICONS)) {
  if (!CATEGORIES.includes(category)) problems.push(`Unknown category ${category}`);
  for (const [key, label, keywords] of ICONS[category]) {
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(key) || key.length > 50) problems.push(`Bad key ${key}`);
    if (seen.has(key)) problems.push(`Duplicate key ${key}`);
    seen.add(key);
    if (labels.has(label.toLowerCase())) problems.push(`Duplicate label ${label}`);
    labels.add(label.toLowerCase());
    if (/slack|outlook|ipad|iphone|microsoft|google|amazon|facebook|twitter|whatsapp|dropbox|apple|android|windows/i.test(`${key} ${label} ${keywords}`) || key.startsWith('brand-')) problems.push(`Trademarked name in ${key}`);
    const file = join(tabler, 'icons', 'outline', `${key}.svg`);
    if (!existsSync(file)) {
      problems.push(`Not in Tabler outline set: ${key}`);
      continue;
    }
    const svg = readFileSync(file, 'utf8');
    const inner = svg
      .replace(/^[\s\S]*?<svg[^>]*>/, '')
      .replace(/<\/svg>\s*$/, '')
      .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, '')
      .replace(/\s+/g, ' ')
      .replace(/> </g, '><')
      .replace(/ \/>/g, '/>')
      .trim();
    // Only plain shapes: no scripts, styles, links or event handlers can ever ride along in the bundled data.
    if (inner.includes("'")) problems.push(`Quote in ${key}`);
    if (!/^(<(path|circle|rect|line|polyline|polygon|ellipse)( [a-z-]+="[^"<>]*")*\/>)+$/.test(inner)) problems.push(`Unexpected SVG content in ${key}`);
    icons.push({ key, label, category, keywords, inner });
  }
}
if (!seen.has(DEFAULT_ICON_KEY)) problems.push(`Default icon ${DEFAULT_ICON_KEY} is not in the library`);
for (const c of CATEGORIES) if (!ICONS[c]?.length) problems.push(`Empty category ${c}`);
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

const sorted = [...icons].sort(
  (a, b) => CATEGORIES.indexOf(a.category) - CATEGORIES.indexOf(b.category) || a.label.localeCompare(b.label) || a.key.localeCompare(b.key),
);

const contract = {
  $comment:
    'GENERATED by tools/icons/generate.mjs from tools/icons/catalog.mjs. Do not edit. Allowed values of TaskType.IconKey; icons are Tabler Icons (MIT), outline set.',
  source: `@tabler/icons ${tablerVersion} (outline)`,
  defaultKey: DEFAULT_ICON_KEY,
  categories: CATEGORIES,
  icons: sorted.map(({ key, label, category, keywords }) => ({ key, label, category, keywords })),
};
writeFileSync(join(root, 'contracts/task-type-icons.json'), JSON.stringify(contract, null, 2) + '\n');

const header = `// GENERATED by tools/icons/generate.mjs - do not edit. See docs/ux/task-type-icons.md.
// Icons: Tabler Icons ${tablerVersion} (outline), MIT License, Copyright (c) 2020-2026 Paweł Kuna. Licence text: TABLER-ICONS-LICENSE.txt in this folder.
`;
const q = (s) => JSON.stringify(s);
const outDir = join(root, 'frontend/src/app/shared/icons');
writeFileSync(
  join(outDir, 'task-type-icon-paths.generated.ts'),
  `${header}
/** Icon key to the inner markup of a 24x24 outline SVG (stroke = currentColor, stroke-width 2, round caps/joins). */
export const TASK_TYPE_ICON_PATHS: Readonly<Record<string, string>> = {
${sorted.map((i) => `  ${q(i.key)}: '${i.inner}',`).join('\n')}
};
`,
);
writeFileSync(
  join(outDir, 'task-type-icon-catalog.generated.ts'),
  `${header}
export const TASK_TYPE_ICON_DEFAULT_KEY = ${q(DEFAULT_ICON_KEY)};

export const TASK_TYPE_ICON_CATEGORIES: readonly string[] = ${JSON.stringify(CATEGORIES)};

export interface TaskTypeIconDef {
  readonly key: string;
  readonly label: string;
  readonly category: string;
  readonly keywords: string;
}

export const TASK_TYPE_ICON_CATALOG: readonly TaskTypeIconDef[] = [
${sorted.map((i) => `  { key: ${q(i.key)}, label: ${q(i.label)}, category: ${q(i.category)}, keywords: ${q(i.keywords)} },`).join('\n')}
];
`,
);
const counts = Object.fromEntries(CATEGORIES.map((c) => [c, sorted.filter((i) => i.category === c).length]));
console.log(`Generated ${sorted.length} icons from @tabler/icons ${tablerVersion}`, counts);
